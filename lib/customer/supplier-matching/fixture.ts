import type { InvitedSupplier, MatchingTender, ScoreFactor } from './model'

function factor(
  id: string,
  score: number,
  reason: string,
  missing = false,
  missingLabel?: string,
): ScoreFactor {
  return { id, score, reason, missing, missingLabel }
}

function supplier(
  input: Omit<InvitedSupplier, 'profileHref'> & { id: string },
): InvitedSupplier {
  return {
    ...input,
    profileHref: `/supplier-comparison/${input.id}`,
  }
}

